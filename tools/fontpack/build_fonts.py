"""Generate the device's LVGL bitmap fonts.

usage: python build_fonts.py fonts.json

Why not a generic converter: on this e-ink panel the same glyphs are shown twice, first
as pure black/white (fast refresh), then with two grey levels added (overlay pass). So
each outline is grid-fitted the way a 1-bit font would be (FreeType's mono hinting, with
the font's own instructions where it has good ones), and only then anti-aliased and
stored at 2 bits per pixel. Thresholding the result at 50 % gives a clean, even 1-bit
glyph; the two middle levels only smooth curves and diagonals.

Output: one LVGL "fmt_txt" C file per font plus ct_fonts.h, written to the out_dir named
in the config. All fonts of one pixel size share the same line height and baseline, so
runs in different fonts line up.
"""
import json
import sys
from pathlib import Path

import freetype

FT = freetype

PUNCT = (
    "·×÷±°−–—…‘’“”‹›•"
    "←↑→↓✓✗■□▶●○"
    "　、。〈〉《》「」『』【】〔〕"
    "！（），．：；？～￥"
)


def gb2312_level1():
    out = []
    for hi in range(0xB0, 0xD8):
        for lo in range(0xA1, 0xFF):
            if hi == 0xD7 and lo > 0xF9:
                continue
            out.append(bytes([hi, lo]).decode("gb2312"))
    return out


def scan_sources(root, dirs):
    found = set()
    for d in dirs:
        for path in (root / d).rglob("*"):
            if path.suffix in {".c", ".h", ".ts"} and "fonts" not in path.parts and "node_modules" not in path.parts:
                found.update(ch for ch in path.read_text(encoding="utf-8", errors="ignore") if ord(ch) > 0x7F)
    return found


def build_charset(cfg, root, cjk):
    chars = {chr(c) for c in range(0x20, 0x7F)}
    chars.update(PUNCT)
    chars.update(cfg.get("extra", ""))
    if cjk:
        chars.update(gb2312_level1())
        chars.update(scan_sources(root, cfg.get("scan", [])))
    else:
        chars.update(ch for ch in scan_sources(root, cfg.get("scan", [])) if ord(ch) < 0x2E80)
    return sorted(chars)


def render_font(spec, chars):
    face = FT.Face(spec["path"], index=spec.get("index", 0))
    face.set_pixel_sizes(0, spec["size"])
    flags = FT.FT_LOAD_TARGET_MONO
    if spec.get("hinting") != "native":
        flags |= FT.FT_LOAD_FORCE_AUTOHINT
    glyphs, missing = [], []
    for ch in chars:
        if ch != " " and face.get_char_index(ord(ch)) == 0:
            if ord(ch) < 0x7F:
                raise SystemExit(f"{spec['name']}: font has no glyph for ASCII {ch!r}")
            missing.append(ch)
            continue
        face.load_char(ch, flags)
        g = face.glyph
        g.render(FT.FT_RENDER_MODE_NORMAL)
        bm = g.bitmap
        w, h = bm.width, bm.rows
        buf = bytes(bm.buffer)
        rows = [buf[y * bm.pitch:y * bm.pitch + w] for y in range(h)]
        glyphs.append({
            "ch": ch, "w": w, "h": h, "left": g.bitmap_left, "top": g.bitmap_top,
            "adv": g.advance.x / 64.0, "rows": rows,
        })
    return glyphs, missing


def pack_2bpp(glyph):
    """Pixels as a continuous big-endian bit stream, 2 bits each, no row padding."""
    out, acc, nbits = bytearray(), 0, 0
    for row in glyph["rows"]:
        for cov in row:
            acc = (acc << 2) | ((cov * 3 + 127) // 255)
            nbits += 2
            if nbits == 8:
                out.append(acc)
                acc, nbits = 0, 0
    if nbits:
        out.append(acc << (8 - nbits))
    return bytes(out)


def emit_c(spec, glyphs, line_height, base_line, out_path):
    name = spec["name"]
    bitmaps, dsc = bytearray(), []
    for g in glyphs:
        data = pack_2bpp(g) if g["w"] and g["h"] else b""
        dsc.append((len(bitmaps), round(g["adv"] * 16), g["w"], g["h"], g["left"], g["top"] - g["h"]))
        bitmaps += data
    if len(bitmaps) >= 1 << 20:
        raise SystemExit(f"{name}: bitmap data over 1 MB, split the font")

    ascii_glyphs = [g for g in glyphs if 0x20 <= ord(g["ch"]) < 0x7F]
    rest = [g for g in glyphs if ord(g["ch"]) >= 0x7F]
    assert len(ascii_glyphs) == 95 and glyphs[:95] == ascii_glyphs, "ASCII must come first and be complete"

    lines = [f"/* Generated by tools/fontpack/build_fonts.py. Do not edit.",
             f" * {Path(spec['path']).name}, {spec['size']} px, 2 bpp, {len(glyphs)} glyphs. */",
             '#include "lvgl.h"', ""]
    lines.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmaps), 32):
        lines.append(",".join(str(b) for b in bitmaps[i:i + 32]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    lines.append("{.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
    for idx, adv, w, h, ox, oy in dsc:
        lines.append(f"{{.bitmap_index = {idx}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, .ofs_x = {ox}, .ofs_y = {oy}}},")
    lines.append("};")
    lines.append("")

    cmap_count = 1
    if rest:
        start = ord(rest[0]["ch"])
        span = ord(rest[-1]["ch"]) - start + 1
        if span > 0xFFFF:
            raise SystemExit(f"{name}: non-ASCII characters span more than 65535 code points")
        lines.append("static const uint16_t unicode_list_1[] = {")
        offs = [ord(g["ch"]) - start for g in rest]
        for i in range(0, len(offs), 24):
            lines.append(",".join(str(o) for o in offs[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
        cmap_count = 2
    lines.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    lines.append("{.range_start = 32, .range_length = 95, .glyph_id_start = 1, .unicode_list = NULL,"
                 " .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},")
    if rest:
        lines.append(f"{{.range_start = {start}, .range_length = {span}, .glyph_id_start = 96,"
                     f" .unicode_list = unicode_list_1, .glyph_id_ofs_list = NULL, .list_length = {len(rest)},"
                     " .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY},")
    lines.append("};")
    lines.append("")
    lines.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    lines.append("    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,")
    lines.append(f"    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = {cmap_count}, .bpp = 2,")
    lines.append("    .kern_classes = 0, .bitmap_format = 0,")
    lines.append("};")
    lines.append("")
    fallback = spec.get("fallback")
    if fallback:
        lines.append(f"extern const lv_font_t {fallback};")
    lines.append(f"const lv_font_t {name} = {{")
    lines.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    lines.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    lines.append(f"    .line_height = {line_height}, .base_line = {base_line},")
    lines.append("    .subpx = LV_FONT_SUBPX_NONE, .underline_position = -2, .underline_thickness = 1,")
    lines.append(f"    .dsc = &font_dsc, .fallback = {'&' + fallback if fallback else 'NULL'}, .user_data = NULL,")
    lines.append("};")
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(bitmaps)


def main():
    cfg_path = Path(sys.argv[1]).resolve()
    cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
    root = cfg_path.parents[2]  # tools/fontpack/fonts.json -> repo root
    out_dir = root / cfg["out_dir"]
    out_dir.mkdir(parents=True, exist_ok=True)

    rendered = []
    for spec in cfg["fonts"]:
        spec = dict(spec, path=str((root / spec["path"]).resolve()))
        chars = build_charset(cfg, root, spec.get("cjk", False))
        glyphs, missing = render_font(spec, chars)
        rendered.append((spec, glyphs, missing))

    # shared vertical metrics per pixel size
    metrics = {}
    for spec, glyphs, _ in rendered:
        asc = max(g["top"] for g in glyphs if g["h"])
        desc = max(g["h"] - g["top"] for g in glyphs if g["h"])
        a, d = metrics.get(spec["size"], (0, 0))
        metrics[spec["size"]] = (max(a, asc), max(d, desc))

    total = 0
    for spec, glyphs, missing in rendered:
        asc, desc = metrics[spec["size"]]
        size = emit_c(spec, glyphs, asc + desc, desc, out_dir / f"{spec['name']}.c")
        total += size
        note = f", {len(missing)} not in font" if missing else ""
        print(f"{spec['name']}: {len(glyphs)} glyphs, {size / 1024:.0f} KB bitmap, "
              f"line {asc + desc} px, baseline {desc} px{note}")

    header = ["/* Generated by tools/fontpack/build_fonts.py. Do not edit. */",
              "#ifndef CT_FONTS_H", "#define CT_FONTS_H", '#include "lvgl.h"', ""]
    header += [f"LV_FONT_DECLARE({spec['name']})" for spec, _, _ in rendered]
    header += ["", "#endif"]
    (out_dir / "ct_fonts.h").write_text("\n".join(header) + "\n", encoding="utf-8")
    print(f"total bitmap data: {total / 1024 / 1024:.2f} MB -> {out_dir}")


if __name__ == "__main__":
    main()
